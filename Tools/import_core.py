#!/usr/bin/env python3
"""Reproducibly adapt pinned upstream routines to per-instance, I/O-free C.

No network access. The checked-in Vendor files are the reference; arithmetic
and algorithm bodies are retained except the documented overflow fixes.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'Vendor/EdgeOMatic'


def function(source, name):
    match = re.search(r'(?m)^(?:static )?[\w* ]+\b' + name + r'\(([^;{}]*?)\)\s*\{', source)
    assert match, name
    start = source.index('{', match.start())
    depth = 1
    end = start + 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[match.start():start].strip(), source[start + 1:end - 1]


def render(source, name, rename=None, edit=lambda body: body):
    signature, body = function(source, name)
    body = edit(body)
    for old, new in CALLS.items():
        body = re.sub(r'\b' + re.escape(old) + r'\(', new + '(engine, ', body)
    body = body.replace('(engine, )', '(engine)')
    name_out = rename or name
    signature = re.sub(r'\b' + name + r'\((.*?)\)',
                       lambda m: name_out + '(EOMEngine *engine' +
                       ('' if m[1].strip() in ('void', '') else ', ' + m[1]) + ')', signature)
    if not signature.startswith('static '):
        signature = 'static ' + signature
    return signature + ' {' + body + '}\n'


detector = (VENDOR / 'src/orgasm_detection.c').read_text()
controller = (VENDOR / 'src/orgasm_control.c').read_text()
ramp = (VENDOR / 'src/vibration_modes/ramp_stop_controller.c').read_text()
DETECTION = ['_now_ms', '_update_baseline', '_detect_peak', '_record_peak',
             '_check_rhythmic', '_reset_to_idle', 'orgasm_detection_init', 'orgasm_detection_tick']
CALLS = {name: name for name in DETECTION}
CALLS.update({f'ramp_{name}': f'ramp_{name}' for name in ['start', 'increment', 'tick', 'stop', 'on_edge']})


def edit_detector(body):
    return body.replace('det.peak_count++;', 'if (det.peak_count < 255) det.peak_count++;')


def edit_arousal(body):
    body = body[:body.index('    // Update accessories:')]
    old = 'arousal_state.arousal + (arousal_state.last_value - arousal_state.peak_start)'
    assert old in body
    return body.replace(old, 'saturate((uint32_t)arousal_state.arousal + (arousal_state.last_value - arousal_state.peak_start))')


def edit_motor(body):
    a = body.index('    if (output_state.output_mode == OC_PLUGIN_CONTROL)')
    b = body.index('    controller->tick', a)
    body = body[:a] + body[b:]
    body = body.replace('controller->', 'ramp_').replace('random()', 'next_random(engine)')
    body = body.replace('orgasm_control_get_motor_speed()', '(uint8_t)output_state.motor_speed')
    return body


prefix = (ROOT / 'Tools/core_prefix.c').read_text()
suffix = (ROOT / 'Tools/core_suffix.c').read_text()
parts = ['// Generated by Tools/import_core.py; see Vendor/EdgeOMatic/LICENSE.\n', prefix]
for name in DETECTION:
    parts.append(render(detector, name, edit=edit_detector))
for name in ['start', 'increment', 'tick', 'stop', 'on_edge']:
    parts.append(render(ramp, name, 'ramp_' + name, edit=lambda body: body.replace('state.', 'engine->ramp.')))
parts.append(render(controller, 'orgasm_control_updateArousal', edit=edit_arousal))
parts.append(render(controller, 'orgasm_control_updateMotorSpeed', edit=edit_motor))
parts.append(suffix)
output = ROOT / 'Sources/EOMCore/EOMCore.c'
output.write_text('\n'.join(parts))
print('Generated', output.relative_to(ROOT))
